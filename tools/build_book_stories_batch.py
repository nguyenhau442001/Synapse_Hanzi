def main():
    stories = build_stories()
    manifest_path = READINGS_DIR / "manifest.json"

    with open(manifest_path, "r", encoding="utf-8") as f:
        manifest = json.load(f)

    # Index by ID in manifest
    manifest_dict = {item["id"]: item for item in manifest}

    for story in stories:
        sid = story["id"]
        story_file = READINGS_DIR / "hsk4" / f"{sid}.json"
        with open(story_file, "w", encoding="utf-8") as f:
            json.dump(story, f, ensure_ascii=False, indent=2)
        print(f"[+] Wrote story: {story_file.name}")

        entry = {
            "id": sid,
            "level": story["level"],
            "series": "wanwu",
            "series_title": "万物有意思",
            "series_title_vi": "Vạn vật thú vị",
            "title": story["title"],
            "topic": story["topic"],
            "topic_vi": story["topic_vi"],
            "icon": story["icon"],
            "estimatedMinutes": story["estimatedMinutes"],
            "description_vi": story["description_vi"],
            "sentence_count": len(story["sentences"]),
            "sentences_count": len(story["sentences"]),
            "spotlight_count": len(story["vocabulary_spotlight"]),
            "words_count": sum(
                len(s.get("tokens", [])) for s in story["sentences"]
            ),
            "file": f"database/readings/hsk4/{sid}.json",
            "path": f"database/readings/hsk4/{sid}.json",
        }

        # Update or insert
        if sid in manifest_dict:
            # Update in place
            idx = next(i for i, m in enumerate(manifest) if m["id"] == sid)
            manifest[idx] = entry
        else:
            # Insert after previous story or at the end of HSK4
            last_hsk4_idx = max(
                i for i, m in enumerate(manifest) if m["level"] == "HSK4"
            )
            manifest.insert(last_hsk4_idx + 1, entry)
            manifest_dict[sid] = entry

    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    print(f"[✓] Manifest successfully updated with {len(stories)} book stories.")


if __name__ == "__main__":
    main()
