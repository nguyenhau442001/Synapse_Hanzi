#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getManifest } from 'workbox-build';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

export async function buildPwaServiceWorker() {
  const versionFile = path.join(ROOT, 'VERSION');
  const version = fs.readFileSync(versionFile, 'utf8').trim();

  // 1. Calculate Content Hash SHA-256 for all precache assets using Workbox
  const { manifestEntries, count, size, warnings } = await getManifest({
    globDirectory: ROOT,
    globPatterns: [
      'index.html',
      'assets/flashcards.css',
      'assets/js/preact/islands.js',
      'assets/js/preact/chunks/*.js',
      'assets/js/hanviet-dict.js',
      'assets/js/fast-review-worker.js',
      'assets/images/*.{svg,png}',
      'config/pwa-manifest.json'
    ],
    globIgnores: [
      'node_modules/**',
      'dist/**',
      'database/**',
      'tests/**',
      'tools/**'
    ]
  });

  if (warnings && warnings.length > 0) {
    console.warn('PWA build warnings:', warnings);
  }

  // 2. Generate modern, robust sw.js with declarative runtime caching
  const swTemplate = `// Auto-generated Service Worker by tools/build_pwa.mjs (Workbox Engine)
// Do not edit this file manually. Run: npm run build:pwa
const APP_VERSION = '${version}';
const CACHE_NAME = 'hsk-flashcards-v' + APP_VERSION;
const DATA_CACHE_NAME = 'hsk-data-v18';

// Precache Manifest with automatic SHA-256 content hashes
const PRECACHE_MANIFEST = ${JSON.stringify(manifestEntries, null, 2)};

const APP_SHELL_URL = new URL('./index.html', self.registration.scope).href;
const ROOT_SHELL_URL = new URL('./', self.registration.scope).href;

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    const urlsToCache = [
      APP_SHELL_URL,
      ROOT_SHELL_URL,
      ...PRECACHE_MANIFEST.map(entry => {
        const u = new URL('./' + entry.url, self.registration.scope);
        if (entry.revision) {
          u.searchParams.set('__wb_rev', entry.revision);
        }
        return u.href;
      })
    ];
    await Promise.allSettled(urlsToCache.map(url => cache.add(url)));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(
      names
        .filter(name =>
          (name.startsWith('hsk-flashcards-') && name !== CACHE_NAME) ||
          (name.startsWith('hsk-data-') && name !== DATA_CACHE_NAME)
        )
        .map(name => caches.delete(name))
    );
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);

  if (url.origin !== self.location.origin) return;

  // Version probe and reading manifest: always hit the network, never use stale cache.
  if (url.pathname.endsWith('/VERSION')) return;
  if (url.pathname.endsWith('/manifest.json')) return;

  // Bypass Service Worker for Range requests, media streaming (audio/video), and neural models.
  // Cache Storage API cannot cache 206 Partial Content, and returning 200 causes MEDIA_ELEMENT_ERROR.
  // Large neural models are stored in IndexedDB by SpeechModelManager to avoid quota exhaustion.
  if (
    request.headers.has('range') ||
    request.destination === 'audio' ||
    request.destination === 'video' ||
    url.pathname.includes('/assets/audio/') ||
    url.pathname.includes('/assets/models/')
  ) {
    return;
  }

  // Readings (articles, manga transcripts): Network first, cached copy only as offline fallback.
  if (url.pathname.includes('/database/readings/')) {
    event.respondWith((async () => {
      const cache = await caches.open(DATA_CACHE_NAME);
      try {
        const response = await fetch(request, { cache: 'no-cache' });
        if (response.status === 200) await cache.put(request, response.clone());
        return response;
      } catch (err) {
        const cached = await cache.match(request, { ignoreSearch: true });
        if (cached) return cached;
        throw err;
      }
    })());
    return;
  }

  // Data: StaleWhileRevalidate for database vocab JSON
  if (url.pathname.includes('/database/')) {
    event.respondWith((async () => {
      const cache = await caches.open(DATA_CACHE_NAME);
      const cached = await cache.match(request, { ignoreSearch: true });
      const refresh = fetch(request).then(async response => {
        if (response.status === 200) await cache.put(request, response.clone());
        return response;
      });
      if (cached) {
        event.waitUntil(refresh.catch(() => {}));
        return cached;
      }
      return refresh;
    })());
    return;
  }

  // Static Assets: Cache first with network fallback
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.status === 200) await cache.put(request, response.clone());
    return response;
  })());
});

// Update banner version communication channel
self.addEventListener('message', event => {
  if (!event.data || event.data.type !== 'GET_VERSION') return;
  const reply = { type: 'VERSION', version: APP_VERSION };
  if (event.ports && event.ports[0]) event.ports[0].postMessage(reply);
  else if (event.source) event.source.postMessage(reply);
});
`;

  const outputPath = path.join(ROOT, 'sw.js');
  fs.writeFileSync(outputPath, swTemplate, 'utf8');
  console.log(`✓ Generated sw.js: precached ${count} files (${(size / 1024).toFixed(1)} kB) using Workbox`);
}

if (process.argv[1] && process.argv[1].endsWith('build_pwa.mjs')) {
  buildPwaServiceWorker();
}
